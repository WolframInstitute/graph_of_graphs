#!/usr/bin/env python3
"""Compute virtual Euler characteristics from stable graphs and signed forests.

This is a check of the known Smillie--Vogtmann/Borinsky--Vogtmann invariant,
not a new formula for it. All connected stable graph types are generated by
contracting non-loop edges of cubic refinements. A second calculation uses
the formal Gaussian potential in Borinsky--Vogtmann, arXiv:2202.08739, (7).
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from contextlib import redirect_stdout
from fractions import Fraction as Q
from math import factorial
import io
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import gog_generate as gog
from graph_helpers import automorphism_order, forest_polynomial_minus_one


def double_factorial_odd(n: int) -> int:
    result = 1
    for i in range(1, n + 1, 2):
        result *= i
    return result


def contract(matrix: list[list[int]], u: int, v: int) -> list[list[int]]:
    """Contract one non-loop edge, retaining other parallel edges as loops."""
    assert u < v and matrix[u][v] > 0
    vertices = [i for i in range(len(matrix)) if i != v]
    images = {i: vertices.index(u if i == v else i) for i in range(len(matrix))}
    result = [[0] * len(vertices) for _ in vertices]
    removed = False
    for a, b in gog.edges_from_matrix(matrix):
        if not removed and (a, b) == (u, v):
            removed = True
            continue
        x, y = images[a], images[b]
        result[x][y] += 1
        if x != y:
            result[y][x] += 1
    assert removed
    return result


def stable_graphs(rank: int, backend: str):
    n = 2 * rank - 2
    with redirect_stdout(io.StringIO()):
        nodes, _, _, complete = gog.generate_graph_of_graph_with_transitions(
            n, jobs=1, backend=backend)
    assert complete and len(nodes) == gog.known_vertex_count(n)
    by_vertices = {n: set(nodes)}
    for v_count in range(n, 1, -1):
        lower = by_vertices.setdefault(v_count - 1, set())
        for code in by_vertices[v_count]:
            matrix = gog.matrix_from_code(code, v_count)
            for u in range(v_count):
                for v in range(u + 1, v_count):
                    if matrix[u][v]:
                        smaller = contract(matrix, u, v)
                        assert len(gog.edges_from_matrix(smaller)) - len(smaller) + 1 == rank
                        assert all(sum(row) + row[i] >= 3 for i, row in enumerate(smaller))
                        lower.add(gog.canonical_code_from_matrix(smaller, backend=backend))
    return by_vertices


def gaussian_euler_coefficients(max_rank: int) -> list[Q]:
    """Log of E exp(-T(sqrt(h) X)/h), evaluated by degree profiles."""
    z = [Q(1)] + [Q(0)] * (max_rank - 1)
    for k in range(1, max_rank):
        def profiles(d: int, remaining: int, vertices: int, weight: Q) -> Q:
            if remaining == 0:
                return weight * double_factorial_odd(2 * k + 2 * vertices - 1)
            if d - 2 > remaining:
                return Q(0)
            total = Q(0)
            vertex_weight = Q((-1) ** (d + 1), d * (d - 1))
            for count in range(remaining // (d - 2) + 1):
                total += profiles(d + 1, remaining - count * (d - 2),
                                  vertices + count,
                                  weight * vertex_weight ** count / factorial(count))
            return total

        z[k] = profiles(3, 2 * k, 0, Q(1))
    connected = [Q(0)] * max_rank
    for k in range(1, max_rank):
        connected[k] = z[k] - sum(
            (Q(i, k) * connected[i] * z[k-i] for i in range(1, k)), Q(0))
    return connected


def check(rank: int, backend: str, expected: Q) -> dict:
    by_vertices = stable_graphs(rank, backend)
    contributions: defaultdict[int, Q] = defaultdict(Q)
    rows = []
    for vertices, codes in sorted(by_vertices.items()):
        for code in sorted(codes):
            matrix = gog.matrix_from_code(code, vertices)
            aut = automorphism_order(matrix)
            forest_sum = forest_polynomial_minus_one(matrix)
            contributions[vertices] += Q(forest_sum, aut)
            rows.append({'vertices': vertices, 'code': list(code),
                         'automorphism_order': aut, 'signed_forest_sum': forest_sum})
    value = sum(contributions.values(), Q(0))
    assert value == expected, (rank, value, expected)
    print(f'rank {rank}: {sum(map(len, by_vertices.values()))} stable graph types; '
          f'virtual Euler characteristic {value}', flush=True)
    return {'rank': rank, 'stable_graph_types': sum(map(len, by_vertices.values())),
            'types_by_vertices': {str(v): len(c) for v, c in sorted(by_vertices.items())},
            'contribution_by_vertices': {str(v): str(c) for v, c in sorted(contributions.items())},
            'virtual_euler_characteristic': str(value),
            'independent_formal_gaussian_coefficient': str(expected), 'graphs': rows}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--max-rank', type=int, default=5)
    parser.add_argument('--backend', choices=['native', 'python'], default='native')
    parser.add_argument('--json', type=Path)
    args = parser.parse_args()
    if args.max_rank < 2:
        parser.error('--max-rank must be at least 2')
    # Independent small checks catch loop and parallel-edge conventions.
    assert forest_polynomial_minus_one([[2]]) == 1
    assert forest_polynomial_minus_one([[0, 3], [3, 0]]) == -2
    assert forest_polynomial_minus_one([[1, 1], [1, 1]]) == 0
    assert automorphism_order([[2]]) == 8
    expected = gaussian_euler_coefficients(args.max_rank)
    assert expected[1] == Q(-1, 24)
    if args.max_rank >= 3:
        assert expected[2] == Q(-1, 48)
    if args.max_rank >= 4:
        assert expected[3] == Q(-161, 5760)
    result = {'method': 'all stable graphs via cubic refinements; signed forests; '
                        'independent formal Gaussian degree-profile calculation',
              'results': [check(r, args.backend, expected[r-1])
                          for r in range(2, args.max_rank + 1)]}
    if args.json:
        args.json.write_text(json.dumps(result, indent=2) + '\n')


if __name__ == '__main__':
    main()
