#!/usr/bin/env python3
"""Measure radius-R ball growth in the graph of graphs.

For fixed N, the graph of graphs is finite, so the quantity of interest is the
pre-saturation growth profile

    B_R(x) = #{y : dist(x,y) <= R}.

This script works on the quotient graph of isomorphism classes generated by
``gog_generate.py``.  It can either read a saved JSON file or generate the full
component on the fly.
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
from collections import deque
from typing import Iterable

from gog_generate import (
    DEFAULT_BACKEND,
    DEFAULT_NAUTY_MODE,
    generate_graph_of_graph,
    known_vertex_count,
)


def adjacency_from_edges(node_count: int, edges: Iterable[tuple[int, int]]) -> list[list[int]]:
    adj = [[] for _ in range(node_count)]
    for a, b in edges:
        if a == b:
            continue
        adj[a].append(b)
        adj[b].append(a)
    return [sorted(set(neigh)) for neigh in adj]


def load_json(path: str) -> tuple[int, bool, list[list[int]]]:
    with open(path, "r", encoding="utf-8") as inp:
        data = json.load(inp)
    node_count = int(data["node_count"])
    edges = [(int(a), int(b)) for a, b in data["edges"]]
    return int(data["N"]), bool(data.get("complete", False)), adjacency_from_edges(node_count, edges)


def generate_adjacency(
    n: int,
    jobs: int | None,
    backend: str,
    nauty_mode: str,
) -> tuple[bool, list[list[int]]]:
    nodes, edges, complete = generate_graph_of_graph(
        n,
        jobs=jobs,
        backend=backend,
        nauty_mode=nauty_mode,
    )
    ordered = sorted(nodes)
    index = {code: i for i, code in enumerate(ordered)}
    indexed_edges = [(index[a], index[b]) for a, b in edges]
    return complete, adjacency_from_edges(len(ordered), indexed_edges)


def ball_profile(adj: list[list[int]], source: int, max_radius: int) -> list[int]:
    dist = [-1] * len(adj)
    dist[source] = 0
    q: deque[int] = deque([source])
    shell = [0] * (max_radius + 1)
    shell[0] = 1
    while q:
        u = q.popleft()
        if dist[u] == max_radius:
            continue
        for v in adj[u]:
            if dist[v] != -1:
                continue
            dist[v] = dist[u] + 1
            shell[dist[v]] += 1
            q.append(v)
    balls = []
    total = 0
    for count in shell:
        total += count
        balls.append(total)
    return balls


def choose_sources(node_count: int, sample: int | None) -> list[int]:
    if sample is None or sample >= node_count:
        return list(range(node_count))
    if sample <= 1:
        return [0]
    # Deterministic evenly spaced sample.  This avoids importing random and
    # makes repeated runs comparable.
    return sorted({round(i * (node_count - 1) / (sample - 1)) for i in range(sample)})


def summarize(values: list[int]) -> tuple[float, int, int]:
    return statistics.fmean(values), min(values), max(values)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("N", type=int, nargs="?", help="number of cubic-graph vertices")
    parser.add_argument("--load", help="read a gog_generate.py JSON file")
    parser.add_argument("--jobs", type=int, default=1)
    parser.add_argument("--backend", choices=("auto", "native", "nauty", "python"), default=DEFAULT_BACKEND)
    parser.add_argument("--nauty-mode", choices=("dense", "sparse", "traces"), default=DEFAULT_NAUTY_MODE)
    parser.add_argument("--max-radius", type=int, default=8)
    parser.add_argument("--sample", type=int, default=None, help="number of evenly spaced centers")
    args = parser.parse_args()

    if args.load:
        n, complete, adj = load_json(args.load)
        if args.N is not None and args.N != n:
            raise ValueError(f"loaded N={n}, but command line requested N={args.N}")
    else:
        if args.N is None:
            raise SystemExit("provide N or --load")
        n = args.N
        complete, adj = generate_adjacency(n, args.jobs, args.backend, args.nauty_mode)

    node_count = len(adj)
    expected = known_vertex_count(n)
    degrees = [len(neigh) for neigh in adj]
    avg_degree = statistics.fmean(degrees)
    branching = avg_degree - 1 if avg_degree > 1 else 0.0

    print()
    if n % 2 == 0:
        print(f"half-order N: {n // 2}  (trivalent vertices: 2N = {n})")
    else:
        print(f"trivalent vertices: {n}")
    print(f"nodes: {node_count}" + (f" expected {expected}" if expected is not None else ""))
    print(f"complete: {complete}")
    print(f"quotient degree: avg={avg_degree:.6g} min={min(degrees)} max={max(degrees)}")
    print(f"naive tree branching avg(deg)-1: {branching:.6g}")
    if branching > 1 and node_count > 1:
        print(f"tree-like saturation scale log_{{avgdeg-1}} |V|: {math.log(node_count, branching):.3f}")

    sources = choose_sources(node_count, args.sample)
    profiles = [ball_profile(adj, source, args.max_radius) for source in sources]

    print()
    print("R  avg_ball  min_ball  max_ball  avg_shell  tree_ball(avg degree)")
    previous_avg = 0.0
    for r in range(args.max_radius + 1):
        column = [profile[r] for profile in profiles]
        avg, lo, hi = summarize(column)
        avg_shell = avg - previous_avg
        previous_avg = avg
        if r == 0:
            tree_ball = 1.0
        elif avg_degree <= 2:
            tree_ball = 1 + avg_degree * r
        else:
            tree_ball = 1 + avg_degree * ((avg_degree - 1) ** r - 1) / (avg_degree - 2)
        print(f"{r:1d}  {avg:8.3f}  {lo:8d}  {hi:8d}  {avg_shell:9.3f}  {tree_ball:19.3f}")


if __name__ == "__main__":
    main()
