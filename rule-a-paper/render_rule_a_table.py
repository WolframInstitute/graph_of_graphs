#!/usr/bin/env python3
"""Render the manuscript's exact-enumeration rows from the audit summary."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


EXPECTED_N = [2, 4, 6, 8, 10, 12, 14]


def latex_integer(value: int) -> str:
    return f"{value:,}".replace(",", "{,}")


def latex_math_integer(value: str) -> str:
    return f"{int(value):,}".replace(",", r"\,")


def latex_rational(value: str) -> str:
    if "/" not in value:
        return latex_math_integer(value)
    numerator, denominator = value.split("/", maxsplit=1)
    return rf"\dfrac{{{latex_math_integer(numerator)}}}{{{latex_math_integer(denominator)}}}"


def latex_seconds(value: float) -> str:
    if value < 0.01:
        return "$<0.01$"
    if value < 100:
        return f"{value:.2f}"
    return f"{value:,.1f}".replace(",", "{,}")


def render(input_path: Path, output_path: Path) -> None:
    with input_path.open("r", encoding="utf-8") as source:
        payload = json.load(source)
    if payload.get("schema") != "rule-a-enumeration-v2":
        raise ValueError("unrecognized enumeration-audit schema")
    if payload.get("all_complete") is not True:
        raise ValueError("audit summary does not mark every search as complete")
    results = payload.get("results")
    if not isinstance(results, list):
        raise ValueError("audit summary has no result list")
    if [row.get("N") for row in results] != EXPECTED_N:
        raise ValueError(f"audit summary must contain exactly N={EXPECTED_N}")

    size_rows: list[str] = []
    bridge_rows: list[str] = []
    for row in results:
        n = int(row["N"])
        classes = int(row["classes"])
        slots = int(row["slots"])
        if slots != 3 * n * classes:
            raise ValueError(f"slot total is inconsistent at N={n}")
        for digest_name in ("states_sha256", "transition_counts_sha256"):
            digest = str(row.get(digest_name, ""))
            if len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
                raise ValueError(f"invalid {digest_name} at N={n}")
        size_values = [
            str(n),
            latex_integer(classes),
            latex_integer(int(row["support_edges"])),
            latex_integer(slots),
            latex_seconds(float(row["audit_seconds"])),
        ]
        bridge_values = [
            str(n),
            rf"${latex_rational(str(row['pi_B0']))}$",
            rf"${latex_rational(str(row['pi_B1']))}$",
            rf"${latex_rational(str(row['bridge_flow']))}$",
            rf"${latex_rational(str(row['bridge_conductance']))}$",
        ]
        size_rows.append(" & ".join(size_values) + r" \\")
        bridge_rows.append(" & ".join(bridge_values) + r" \\")

    lines = [
        "% Generated by render_rule_a_table.py from rule-a-enumeration.json.",
        "% Do not edit this file by hand.",
        r"\newcommand{\RuleASizeRows}{%",
        *size_rows,
        "}",
        r"\newcommand{\RuleABridgeRows}{%",
        *bridge_rows,
        "}",
    ]

    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    render(arguments.input, arguments.output)


if __name__ == "__main__":
    main()
